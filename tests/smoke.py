# Checkpoint 1 smoke test: python3 -m http.server 8099 (in project root), then python3 tests/smoke.py
import sys, time
from playwright.sync_api import sync_playwright
URL = "http://localhost:8099/"
ok = True
def check(name, cond):
    global ok; ok &= bool(cond); print(("PASS " if cond else "FAIL ") + name)
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={"width":390,"height":844}, service_workers="allow")
    pg = ctx.new_page(); errs=[]
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto(URL); pg.wait_for_selector("h1")
    check("welcome shown when no session", "Go outside" in pg.inner_text("h1"))
    check("email form validates", (pg.fill("#em","") or True) and (pg.click("button[type=submit]") or True) and "Enter your email" in pg.inner_text("#authMsg"))
    pg.click("[data-act=google]"); pg.wait_for_selector("#authMsg:not(:empty)")
    check("google without config fails gracefully", len(pg.inner_text("#authMsg"))>5)
    pg.click("[data-act=local]"); pg.wait_for_selector(".splash", timeout=3000); check("splash with leaf icon shown after sign-in", True); pg.wait_for_selector("text=Ready to go outside?")
    check("continue locally reaches home", True)
    pg.wait_for_function("navigator.serviceWorker.controller !== null", timeout=15000)
    check("service worker controls page", True)
    manifest = pg.evaluate("fetch('manifest.webmanifest').then(r=>r.json())")
    check("manifest valid", manifest["display"]=="standalone" and len(manifest["icons"])==3)
    pg.reload(); pg.wait_for_selector("text=Ready to go outside?")
    check("session restored after reload", True)
    ctx.set_offline(True)
    pg.reload(); pg.wait_for_selector("text=Ready to go outside?", timeout=10000)
    check("offline launch restores session + shell", True)
    pg.click("a[href='#/you']"); pg.wait_for_selector("text=On this device only")
    check("you screen renders offline", "Offline" in pg.inner_text("main"))
    pg.screenshot(path="/tmp/you.png")
    ctx.set_offline(False)
    pg.click("a[href='#/home']"); pg.wait_for_selector("text=Give me a quest"); pg.click("text=Choose what I feel like"); pg.wait_for_selector("#qf")
    pg.click("input[name=company][value=family]"); pg.click("button[type=submit]"); pg.wait_for_selector("ol.steps")
    check("quest created from form", pg.locator("ol.steps li").count() >= 3)
    title = pg.inner_text("h1"); ctx.set_offline(True)
    pg.click("#go"); pg.wait_for_selector("#away"); pg.reload(); pg.wait_for_selector("#away"); pg.click("#away"); pg.wait_for_selector("ol.steps")
    check("active quest survives offline reload", pg.inner_text("h1") == title and "In progress" in pg.inner_text("main"))
    pg.screenshot(path="/tmp/quest.png"); ctx.set_offline(False)
    pg.click("#drop"); pg.wait_for_selector("text=Give me a quest"); check("dropping returns to empty home", True)
    pg.click("a[href='#/home']"); pg.wait_for_selector("text=Ready to go outside?"); pg.wait_for_timeout(700); pg.screenshot(path="/tmp/home.png")
    pg.once("dialog", lambda d: d.accept())
    pg.click("a[href='#/you']"); pg.click("#out"); pg.wait_for_selector("text=Go outside")
    check("leaving profile returns to welcome", True)
    pg.screenshot(path="/tmp/welcome.png")
    check("no uncaught page errors", not errs)
    if errs: print(errs)
    b.close()
sys.exit(0 if ok else 1)
